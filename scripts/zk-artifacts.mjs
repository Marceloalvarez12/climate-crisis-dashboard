import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, URL } from "node:url"

export const root = fileURLToPath(new URL("../", import.meta.url))
export const build = path.join(root, "zk/build")
export const circuit = "zk/circuits/zone_membership.circom"
export const rustKey = "zk/contracts/zone_verifier/src/verification_key.rs"
export const artifacts = [
  "zk/build/zone_membership_js/zone_membership.wasm",
  "zk/build/zone_membership_final.zkey",
  "zk/build/verification_key.json",
  circuit,
  rustKey,
]

export function digest(relativePath) {
  const bytes = readFileSync(path.join(root, relativePath))
  // Git may convert source newlines on Windows; binary digests stay exact.
  const content = /\.(circom|rs)$/.test(relativePath)
    ? bytes.toString("utf8").replace(/\r\n/g, "\n") : bytes
  return createHash("sha256").update(content).digest("hex")
}

const hex = (n) => BigInt(n).toString(16).padStart(64, "0")
const g1 = (point) => hex(point[0]) + hex(point[1])
// Soroban expects the extension-field coefficients in c1, c0 order.
const g2 = (point) => hex(point[0][1]) + hex(point[0][0]) + hex(point[1][1]) + hex(point[1][0])
const bytes = (encoded) => encoded.match(/../g).map((b) => `0x${b}`).join(", ")

export function renderRustKey(vk) {
  return [
    "// Generated by npm run zk:setup. Must match zk/build/verification_key.json.",
    `const VK_ALPHA: [u8; BN254_G1_SERIALIZED_SIZE] = [${bytes(g1(vk.vk_alpha_1))}];`,
    ...["BETA", "GAMMA", "DELTA"].map((name) =>
      `const VK_${name}: [u8; BN254_G2_SERIALIZED_SIZE] = [${bytes(g2(vk[`vk_${name.toLowerCase()}_2`]))}];`),
    `const VK_IC: [[u8; BN254_G1_SERIALIZED_SIZE]; ${vk.IC.length}] = [`,
    ...vk.IC.map((point) => `    [${bytes(g1(point))}],`),
    "];", "",
  ].join("\n")
}
